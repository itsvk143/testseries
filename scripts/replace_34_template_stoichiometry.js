async function replaceRemaining34() {
  const uri = process.env.MONGODB_URI;
  if (!uri) throw new Error("MONGODB_URI not found");

  const client = new MongoClient(uri);
  await client.connect();
  console.log("Connected to MongoDB Atlas.");

  const db = client.db();
  const col = db.collection("questionBank");

  // Query the remaining template loop questions
  const templateDocs = await col.find({
    subject: "Chemistry",
    chapter: /some basic concept/i,
    subTopic: "Stoichiometry",
    $or: [
      { question: /How many moles of \$\\text\{O\}_2\$ are required for the complete combustion of/ },
      { question: /What is the mass of \$\\text\{CO\}_2\$ liberated by the complete thermal decomposition of/ },
      { question: /What volume of hydrogen gas at STP is liberated when/ }
    ]
  }).toArray();

  console.log(`Found ${templateDocs.length} remaining template loop questions in Stoichiometry.`);

  const newQuestions = get34UniqueStoichiometryQuestions();
  console.log(`Loaded ${newQuestions.length} unique authentic replacement questions.`);

  if (templateDocs.length !== newQuestions.length) {
    throw new Error(`Count mismatch: found ${templateDocs.length} docs, but have ${newQuestions.length} replacements.`);
  }

  const bulkOps = templateDocs.map((doc, idx) => {
    const q = newQuestions[idx];
    return {
      updateOne: {
        filter: { _id: doc._id },
        update: {
          $set: {
            question: q.question,
            options: q.options,
            correctAnswer: q.correctAnswer,
            correctOption: q.correctOption,
            explanation: q.explanation,
            difficulty: q.difficulty,
            questionType: q.questionType,
            type: q.type,
            source: q.source,
            subTopic: "Stoichiometry",
            marks: 4,
            negativeMarks: 1,
            cognitiveLevel: "Problem Solving & Calculation",
            targetExams: ["NEET", "JEE Main"],
            updatedAt: new Date()
          }
        }
      }
    };
  });

  const res = await col.bulkWrite(bulkOps);
  console.log(`Bulk update complete! Modified: ${res.modifiedCount}`);

  // Verification
  const remaining = await col.countDocuments({
    subject: "Chemistry",
    chapter: /some basic concept/i,
    $or: [
      { question: /According to the balanced equation/ },
      { question: /How many moles of \$\\text\{O\}_2\$ are required for the complete combustion of/ },
      { question: /What is the mass of \$\\text\{CO\}_2\$ liberated by the complete thermal decomposition of/ }
    ]
  });

  console.log(`Remaining repetitive/template questions: ${remaining}`);
  await client.close();
}

